// Helper Function สำหรับดึงอำเภอของจังหวัด
function getDistrictsByProvince(provinceName) {
  const provObj = THAILAND_ADDRESS_DATA[provinceName];
  if (!provObj) return [];
  const districts = Object.keys(provObj);
  if (districts.length === 0) {
    return ["เมือง" + provinceName, "อำเภอทั่วไป"];
  }
  return districts;
}

// Helper Function สำหรับดึงตำบลของอำเภอในจังหวัด
function getSubdistrictsByDistrict(provinceName, districtName) {
  const provObj = THAILAND_ADDRESS_DATA[provinceName];
  if (!provObj || !provObj[districtName] || provObj[districtName].length === 0) {
    return ["ในเมือง", "ตำบลทั่วไป"];
  }
  return provObj[districtName];
}

